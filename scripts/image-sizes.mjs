// Writes src/data/imageSizes.ts: the pixel size of every case study image, so
// <img> tags can reserve their space before lazy-loading and the page doesn't
// jump while scrolling (which also throws off chapter jumps).
// Run after adding or replacing images: node scripts/image-sizes.mjs
import sharp from 'sharp'
import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.resolve('public')
const DIR = path.join(ROOT, 'case-studies')

async function walk(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...(await walk(full)))
    // page-NN files are renders of the original PDF and aren't shown on the site
    else if (/\.(webp|jpe?g|png)$/i.test(entry.name) && !/^page-\d+\./.test(entry.name)) out.push(full)
  }
  return out
}

const files = (await walk(DIR)).sort()
const lines = []
for (const file of files) {
  const { width, height } = await sharp(file).metadata()
  const key = path.relative(ROOT, file).split(path.sep).join('/')
  lines.push(`  '${key}': [${width}, ${height}],`)
}

await writeFile(
  path.resolve('src/data/imageSizes.ts'),
  `// Generated by scripts/image-sizes.mjs — do not edit by hand.\n` +
    `export const imageSizes: Record<string, [number, number]> = {\n${lines.join('\n')}\n}\n`,
)
console.log(`Wrote sizes for ${files.length} images`)
